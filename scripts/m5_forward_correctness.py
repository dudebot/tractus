# Tube-state plausibility check (separate state-capture run).
# ---------------------------------------------------------------------------


def _state_plausibility(npz_path: Path) -> dict:
    """Run a per-frame state capture; verify areas > 0, pressures finite,
    section magnitudes (≈ velocities) finite. We re-run the per-sample inner
    body manually for a small subset of frames to read state.

    Cheaper alternative: re-render the audio + read final TDS state, plus
    check that input ``area_cm2`` (post-clamp) is > 0. The MNA solver clamps
    areas at MIN_AREA_CM2 internally; if any post-step pressure or branch
    magnitude is non-finite, the audio would be non-finite too — already
    captured by the NaN sweep gate.
    """
    import jax
    import jax.numpy as jnp
    from tractus_engine_advanced.pipeline import synthesize_dynamic_tube

    data = np.load(npz_path)
    A = np.asarray(data["area_cm2"])
    L = np.asarray(data["length_cm"])
    # Post-clamp check (MIN_AREA_CM2 = 1e-4).
    A_clamped = np.maximum(A, 1e-4)
    areas_positive = bool(np.all(A_clamped > 0))
    lengths_positive = bool(np.all(L > 0))

    audio, final_tds, final_out, final_g = synthesize_dynamic_tube(
        length_cm=jnp.asarray(data["length_cm"]),
        area_cm2=jnp.asarray(data["area_cm2"]),
        wall_mass=jnp.asarray(data["wall_mass"]),
        wall_resistance=jnp.asarray(data["wall_resistance"]),
        wall_stiffness=jnp.asarray(data["wall_stiffness"]),
        samples_per_frame=int(data["samples_per_frame"]),
        glottis_traj=jnp.asarray(data["glottis_traj"]),
    )
    audio.block_until_ready()
    sec = np.asarray(final_tds.section)  # (93, 5)
    br = np.asarray(final_tds.branch)    # (97, 3)
    pressures_finite = bool(np.all(np.isfinite(sec[:, 0])))
    pressure_rates_finite = bool(np.all(np.isfinite(sec[:, 1])))
    velocities_finite = bool(np.all(np.isfinite(br[:, 0])))
    audio_finite = bool(np.all(np.isfinite(np.asarray(audio))))

    return {
        "areas_positive": areas_positive,
        "lengths_positive": lengths_positive,
        "final_pressures_finite": pressures_finite,
        "final_pressure_rates_finite": pressure_rates_finite,
        "final_branch_velocities_finite": velocities_finite,
        "audio_finite": audio_finite,
        "max_abs_pressure": float(np.max(np.abs(sec[:, 0]))),
        "max_abs_branch_magnitude": float(np.max(np.abs(br[:, 0]))),
        "max_abs_audio": float(np.max(np.abs(np.asarray(audio)))),
        "pass": (
            areas_positive and lengths_positive and pressures_finite
            and pressure_rates_finite and velocities_finite and audio_finite
        ),
    }


# ---------------------------------------------------------------------------
# 10K-seed NaN/Inf random-envelope sweep.
# ---------------------------------------------------------------------------


def _nan_sweep(n_seeds: int, batch: int = 32) -> dict:
    """Run ``n_seeds`` random-in-envelope short forwards; count NaN/Inf.

    Envelope: random per-frame perturbations of the area/glottis baselines
    at the *family-level* parameter ranges (matches the corpus envelope).
    Short-window forward (F=4 frames × 50 samples = 200 samples / pass)
    is enough to expose any per-sample NaN: the MNA solver is the only
    state-mutating call on the hot path, and a NaN in the linearized
    inverse propagates within a single sample. Short windows let us
    pack ``batch`` seeds into one ``vmap`` and amortize the JAX dispatch
    overhead — without batching, single-seed forwards are ~2 s each on
    GPU because of XLA stream-launch latency, making 10K infeasible.
    """
    import jax  # noqa: F401
    import jax.numpy as jnp
    from tractus_engine_advanced.pipeline import synthesize_dynamic_tube

    sys.path.insert(0, str(REPO_ROOT / "tractus_controller"))
    from tractus_controller.adapters.r1_inference import load_default_tube
    default = load_default_tube()
    L0 = np.asarray(default["length_cm"], dtype=np.float32)
    A0 = np.asarray(default["area_cm2"], dtype=np.float32)
    Mw0 = np.asarray(default["wall_mass_cgs"], dtype=np.float32)
    Bw0 = np.asarray(default["wall_resistance_cgs"], dtype=np.float32)
    Kw0 = np.asarray(default["wall_stiffness_cgs"], dtype=np.float32)
    g_neutral = np.array(
        [120.0, 8000.0, 0.01, 0.02, 0.05, 1.22, 1.0, 0.05, 0.0, 25.0, -10.0],
        dtype=np.float32,
    )

    F = 4
    SPF = 50

    def _build_one_seed(seed: int):
        sub_rng = np.random.default_rng(seed)
        A_pert = np.broadcast_to(A0[None, :], (F, 93)).copy()
        pm_perturb = sub_rng.uniform(0.001, 6.0, size=(F, 40)).astype(np.float32)
        A_pert[:, 25:65] = pm_perturb
        L_pert = np.broadcast_to(L0[None, :], (F, 93)).copy()
        Mw = np.broadcast_to(Mw0[None, :], (F, 93)).copy()
        Bw = np.broadcast_to(Bw0[None, :], (F, 93)).copy()
        Kw = np.broadcast_to(Kw0[None, :], (F, 93)).copy()
        g = np.broadcast_to(g_neutral[None, :], (F, 11)).copy()
        g[:, 0] = sub_rng.uniform(60.0, 500.0, size=F).astype(np.float32)
        g[:, 1] = sub_rng.uniform(0.0, 18000.0, size=F).astype(np.float32)
        g[:, 2] = sub_rng.uniform(-0.05, 0.3, size=F).astype(np.float32)
        g[:, 3] = sub_rng.uniform(-0.05, 0.3, size=F).astype(np.float32)
        g[:, 4] = sub_rng.uniform(-0.2, 0.2, size=F).astype(np.float32)
        g[:, 6] = sub_rng.uniform(-1.0, 1.0, size=F).astype(np.float32)
        g[:, 7] = sub_rng.uniform(0.0, 1.0, size=F).astype(np.float32)
        g[:, 8] = sub_rng.uniform(-0.5, 0.5, size=F).astype(np.float32)
        g[:, 9] = sub_rng.uniform(0.0, 100.0, size=F).astype(np.float32)
        g[:, 10] = sub_rng.uniform(-40.0, 0.0, size=F).astype(np.float32)
        return L_pert, A_pert, Mw, Bw, Kw, g

    # Compile a vmapped forward at fixed (B, F) shape.
    def _single_forward(l, a, m, b, k, gt):
        audio, _, _, _ = synthesize_dynamic_tube(
            length_cm=l, area_cm2=a,
            wall_mass=m, wall_resistance=b, wall_stiffness=k,
            samples_per_frame=SPF, glottis_traj=gt,
        )
        return audio
    fwd_batched = jax.jit(jax.vmap(_single_forward))

    nan_count = 0
    inf_count = 0
    n_done = 0
    t0 = time.time()
    while n_done < n_seeds:
        n_this = min(batch, n_seeds - n_done)
        # Build batch arrays.
        if n_this < batch:
            # Pad the last batch up to ``batch`` (so the JIT cache hit
            # stays; we trim afterwards).
            pad_n = batch - n_this
        else:
            pad_n = 0
        b_l = np.empty((batch, F, 93), dtype=np.float32)
        b_a = np.empty((batch, F, 93), dtype=np.float32)
        b_m = np.empty((batch, F, 93), dtype=np.float32)
        b_b = np.empty((batch, F, 93), dtype=np.float32)
        b_k = np.empty((batch, F, 93), dtype=np.float32)
        b_g = np.empty((batch, F, 11), dtype=np.float32)
        for j in range(n_this):
            l_, a_, m_, bw_, kw_, g_ = _build_one_seed(n_done + j)
            b_l[j], b_a[j], b_m[j], b_b[j], b_k[j], b_g[j] = l_, a_, m_, bw_, kw_, g_
        # Pad with the last seed (won't affect counts because we slice).
        if pad_n > 0:
            for j in range(n_this, batch):
                b_l[j], b_a[j], b_m[j], b_b[j], b_k[j], b_g[j] = (
                    b_l[n_this - 1], b_a[n_this - 1], b_m[n_this - 1],
                    b_b[n_this - 1], b_k[n_this - 1], b_g[n_this - 1],
                )
        audio = fwd_batched(b_l, b_a, b_m, b_b, b_k, b_g)
        audio.block_until_ready()
        arr = np.asarray(audio)[:n_this]  # only count real seeds
        per_seed_nan = np.any(np.isnan(arr).reshape(n_this, -1), axis=1)
        per_seed_inf = np.any(np.isinf(arr).reshape(n_this, -1), axis=1)
        nan_count += int(np.sum(per_seed_nan))
        inf_count += int(np.sum(per_seed_inf))
        n_done += n_this
        if (n_done % (10 * batch)) == 0 or n_done == n_seeds:
            elapsed = time.time() - t0
            rate = n_done / max(elapsed, 1e-6)
            eta = (n_seeds - n_done) / max(rate, 1e-6)
            print(
                f"  nan_sweep [{n_done}/{n_seeds}] nan={nan_count} inf={inf_count} "
                f"elapsed={elapsed:.1f}s rate={rate:.1f}/s eta={eta:.0f}s"
            )

    return {
        "n_seeds": n_seeds,
        "batch_size": batch,
        "frames": F,
        "samples_per_frame": SPF,
        "nan_count": nan_count,
        "inf_count": inf_count,
        "elapsed_s": time.time() - t0,
        "pass": (nan_count == 0 and inf_count == 0),
    }


# ---------------------------------------------------------------------------
# Saved-fixture parity (deferred — no oracle).
# ---------------------------------------------------------------------------


def _saved_fixture_parity() -> dict:
    """Compare fp32 audio to the pre-deletion m5_oracle fixture set if
    available. DEFERRED to infra/005 fixture-regen; absence is recorded but
    not a hard fail at the correctness/002 level (per task notes)."""
    if not M5_ORACLE_DIR.exists():
        return {
            "available": False,
            "reason": "outputs/fixtures/m5_oracle/ does not exist on this machine",
            "pass": None,
        }
    fixtures = sorted(M5_ORACLE_DIR.glob("*.npz"))
    if not fixtures:
        return {
            "available": False,
            "reason": "outputs/fixtures/m5_oracle/ exists but contains no NPZ files",
            "pass": None,
        }
    # If the directory exists with content, run the comparison.
    rmses = []
    for fp in fixtures[:30]:
        d = np.load(fp)
        # Saved fixture has length_cm, area_cm2, glottis_traj — re-render at fp32.
        import jax.numpy as jnp
        from tractus_engine_advanced.pipeline import synthesize_dynamic_tube
        # Saved fixtures may not include wall arrays — fall back to default.
        if "wall_mass" in d.files:
            Mw = jnp.asarray(d["wall_mass"])
            Bw = jnp.asarray(d["wall_resistance"])
            Kw = jnp.asarray(d["wall_stiffness"])
        else:
            from tractus_controller.adapters.r1_inference import load_default_tube
            tube = load_default_tube()
            T = d["length_cm"].shape[0]
            Mw = jnp.broadcast_to(tube["wall_mass_cgs"][None, :], (T, 93))
            Bw = jnp.broadcast_to(tube["wall_resistance_cgs"][None, :], (T, 93))
            Kw = jnp.broadcast_to(tube["wall_stiffness_cgs"][None, :], (T, 93))
        audio, _, _, _ = synthesize_dynamic_tube(
            length_cm=jnp.asarray(d["length_cm"]),
            area_cm2=jnp.asarray(d["area_cm2"]),
            wall_mass=Mw,
            wall_resistance=Bw,
            wall_stiffness=Kw,
            samples_per_frame=110,
            glottis_traj=jnp.asarray(d["glottis_traj"]),
        )
        audio.block_until_ready()
        rmses.append(_audio_rmse(np.asarray(audio), np.asarray(d["audio"])))
    pass_n = sum(1 for r in rmses if r <= 1e-3)
    return {
        "available": True,
        "n_utt": len(rmses),
        "n_passed": pass_n,
        "rmses": rmses,
        "pass": pass_n >= 27,
    }


# ---------------------------------------------------------------------------
# Main driver.
# ---------------------------------------------------------------------------


def main(argv: list[str]) -> int:
    import argparse
    p = argparse.ArgumentParser()
    p.add_argument("--n-seeds", type=int, default=10000,
                   help="number of seeds in the NaN/Inf sweep (default 10K)")
    p.add_argument("--skip-fp64", action="store_true",
                   help="skip fp64 leg (debug only)")
    p.add_argument("--skip-nan-sweep", action="store_true",
                   help="skip the 10K-seed NaN sweep (debug only)")
    p.add_argument("--n-utterances", type=int, default=30,
                   help="cap number of corpus utterances processed (debug only)")
    args = p.parse_args(argv)

    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    WORK_DIR.mkdir(parents=True, exist_ok=True)

    if not CORPUS_DIR.exists():
        print(f"ERROR: corpus dir missing: {CORPUS_DIR}")
        print("Run scripts/gen_correctness_corpus.py first.")
        return 2

    manifest = json.loads((CORPUS_DIR / "manifest.json").read_text())
    manifest = manifest[: args.n_utterances]
    sr = 44100

    per_utt: list[dict] = []
    print(f"=== correctness/002 M5 forward gate — {len(manifest)} utterances ===\n")

    # Batch fp64 render (single subprocess, amortized JIT).
    if not args.skip_fp64:
        print(f"--- fp64 batch render of {len(manifest)} utterances (subprocess) ---")
        t0_fp64 = time.time()
        _render_fp64_batch(len(manifest))
        print(f"--- fp64 batch render done in {time.time() - t0_fp64:.1f}s ---\n")

    # Per-utterance fp32 + axes + energy + plausibility.
    for ix, m in enumerate(manifest):
        npz_path = REPO_ROOT / m["path"]
        utt = m["utt_id"]
        print(f"[{ix+1:02d}/{len(manifest)}] {utt} ({m['family']}: {m['description']})")
        t_utt = time.time()
        a32 = _render_fp32(npz_path)
        # Save fp32 audio for downstream runbook callers (gitignored).
        np.savez(WORK_DIR / f"{utt}.fp32.npz", audio=a32, sample_rate=np.int32(sr))

        if args.skip_fp64:
            a64 = a32.copy()
            rmse_32_64 = 0.0
            log_mel_l1 = 0.0
        else:
            fp64_npz = WORK_DIR / f"{utt}.fp64.npz"
            a64 = np.load(fp64_npz)["audio"]
            rmse_32_64 = _audio_rmse(a32, a64)
            log_mel_l1 = _log_mel_l1_db(a32, a64, sr)

        d_npz = np.load(npz_path)
        spf = int(d_npz["samples_per_frame"])
        glottis_traj = np.asarray(d_npz["glottis_traj"])
        axes = _source_tract_axes(a32, a64, glottis_traj, spf, sr, family=m["family"])
        energy = _energy_invariant(a32, glottis_traj, spf)
        plaus = _state_plausibility(npz_path)

        # Per correctness/001 precedent: fp32-vs-fp64 audio is "equivalent"
        # if RAW RMSE ≤ 1e-3 OR log-mel L1 ≤ 0.5 dB (the perceptual escape).
        rmse_strict_pass = rmse_32_64 <= 1e-3
        log_mel_pass = log_mel_l1 <= 0.5
        self_consistency_pass = rmse_strict_pass or log_mel_pass

        rec = {
            "utt_id": utt,
            "family": m["family"],
            "description": m["description"],
            "rmse_fp32_vs_fp64": rmse_32_64,
            "log_mel_l1_db_fp32_vs_fp64": log_mel_l1,
            "rmse_fp32_vs_fp64_strict_pass": rmse_strict_pass,
            "log_mel_l1_pass": log_mel_pass,
            "self_consistency_pass": self_consistency_pass,
            "fp32_rms": float(np.sqrt(np.mean(a32.astype(np.float64) ** 2))),
            "fp64_rms": float(np.sqrt(np.mean(a64.astype(np.float64) ** 2))),
            "axes": axes,
            "axes_pass_all": all(axes["axes_pass"].values()),
            "energy_invariant": energy,
            "plausibility": plaus,
            "wall_clock_s": time.time() - t_utt,
        }
        print(f"   rmse32_64={rmse_32_64:.2e} log_mel_L1={log_mel_l1:.2f}dB "
              f"axes_pass={rec['axes_pass_all']} "
              f"f0_rmse_in={axes['f0_rmse_input_cents']:.1f}c "
              f"tilt={axes['tilt_fp32_db_per_oct']:.1f}dB/oct "
              f"fric_db={axes['fric_to_voiced_db_fp32']:.1f} "
              f"energy_pass={energy['pass']} plaus_pass={plaus['pass']}")
        per_utt.append(rec)

    # NaN/Inf sweep.
    if args.skip_nan_sweep:
        nan_sweep = {"skipped": True, "pass": None}
    else:
        print(f"\n=== NaN/Inf sweep ({args.n_seeds} seeds) ===")
        nan_sweep = _nan_sweep(args.n_seeds)

    # Saved-fixture parity (deferred / opportunistic).
    print("\n=== Saved-fixture parity check (DEFERRED if no m5_oracle/) ===")
    fixture_parity = _saved_fixture_parity()
    print(f"   {fixture_parity}")

    # Aggregate gate booleans.
    n_strict_rmse = sum(1 for r in per_utt if r["rmse_fp32_vs_fp64_strict_pass"])
    n_log_mel = sum(1 for r in per_utt if r["log_mel_l1_pass"])
    n_self_consistency = sum(1 for r in per_utt if r["self_consistency_pass"])
    n_axes_all = sum(1 for r in per_utt if r["axes_pass_all"])
    n_energy = sum(1 for r in per_utt if r["energy_invariant"]["pass"])
    n_plaus = sum(1 for r in per_utt if r["plausibility"]["pass"])
    gates = {
        "fp32_vs_fp64_self_consistency": {
            "pass": (
                None if args.skip_fp64
                else n_self_consistency >= max(1, int(0.9 * len(per_utt)))
            ),
            "passed_count_combined": n_self_consistency,
            "passed_count_strict_rmse": n_strict_rmse,
            "passed_count_log_mel": n_log_mel,
            "total": len(per_utt),
            "threshold": (
                "audio RMSE ≤ 1e-3 OR log-mel L1 ≤ 0.5 dB; ≥ 27/30 "
                "(matches correctness/001 escape valve precedent)"
            ),
        },
        "fp32_vs_saved_fixture": {
            "pass": fixture_parity["pass"],
            "deferred_reason": (fixture_parity.get("reason")
                                if fixture_parity.get("pass") is None else None),
            "details": fixture_parity,
        },
        "source_tract_per_axis": {
            "pass": n_axes_all >= len(per_utt),
            "passed_count": n_axes_all,
            "total": len(per_utt),
            "thresholds": {
                "f0_tracks_input_cents": "< 50 cents on voiced frames",
                "tilt_db_per_oct": "in [-20, +2]",
                "frication_absent_db": "< -15 dB vs voiced (M7-conditional; near_clamp family exempt)",
                "nasal_in_range": "in [0, 1] and finite",
                "formants_in_range": "all detected F1..F3 in [90, 5500] Hz",
            },
        },
        "energy_invariant": {
            "pass": n_energy >= len(per_utt),
            "passed_count": n_energy,
            "total": len(per_utt),
            "threshold": "voiced positivity + silence radiation ≤ 5% of voiced",
            "frication_segment_deferred_until_M7": True,
        },
        "tube_state_plausibility": {
            "pass": n_plaus >= len(per_utt),
            "passed_count": n_plaus,
            "total": len(per_utt),
        },
        "nan_inf_sweep": {
            "pass": nan_sweep.get("pass"),
            "details": nan_sweep,
        },
    }

    overall_pass = (
        gates["fp32_vs_fp64_self_consistency"]["pass"] in (True, None)
        and gates["source_tract_per_axis"]["pass"]
        and gates["energy_invariant"]["pass"]
        and gates["tube_state_plausibility"]["pass"]
        and (nan_sweep.get("pass") in (True, None))
    )

    report = {
        "task": "correctness/002 M5 forward-correctness gate",
        "corpus_dir": str(CORPUS_DIR.relative_to(REPO_ROOT)),
        "tea_precision": "fp32",
        "n_utterances": len(per_utt),
        "gates": gates,
        "overall_pass_dispatchable_gates": overall_pass,
        "deferred_gates": ["fp32_vs_saved_fixture (infra/005 fixture-regen blocker)"],
        "per_utterance": per_utt,
    }
    REPORT_PATH.write_text(json.dumps(report, indent=2, default=str))
    print(f"\n=== REPORT ===\n{REPORT_PATH}")
    summary = {k: gates[k]["pass"] for k in gates}
    print(f"gates: {json.dumps(summary, default=str)}")
    print(f"overall (dispatchable): {overall_pass}")
    return 0 if overall_pass else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
