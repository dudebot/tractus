# Energy-conservation invariant.
# ---------------------------------------------------------------------------


def _energy_invariant(audio: np.ndarray, glottis_traj: np.ndarray, samples_per_frame: int) -> dict:
    """Total radiated audio power ≤ total injected source power.

    Approximation: subglottal pressure source = ``glottis_traj[:, PR=1]``;
    proxy injected power per frame ∝ PR² · ΔT. Radiated power ∝ Σ audio² · ΔT.
    The invariant is a strict bound only when wall + radiation losses are
    non-negative (always true for the static linear losses in TEA), so the
    ratio ``E_rad / E_inj`` should be ≤ 1.0 (with 5% tolerance for numeric
    proxy drift). Also: when injected energy is zero (silence), radiated
    energy must be ≤ 5% of voicing-mean — otherwise the system has unstable
    self-oscillation.
    """
    PR = 1
    F = glottis_traj.shape[0]
    pressure = glottis_traj[:, PR]  # dPa per frame
    # Per-frame injected proxy: PR² (dPa²) integrated over frame duration.
    dt_frame = float(samples_per_frame) / 44100.0
    e_inj_per_frame = (pressure**2) * dt_frame  # (F,)

    # Per-frame radiated proxy: Σ audio² over frame samples.
    audio_frames = audio[: F * samples_per_frame].reshape(F, samples_per_frame)
    e_rad_per_frame = np.sum(audio_frames.astype(np.float64) ** 2, axis=1) * (1.0 / 44100.0)

    e_inj = float(np.sum(e_inj_per_frame))
    e_rad = float(np.sum(e_rad_per_frame))

    # Voiced steady-state heuristic: frames where PR > 4000 dPa (typical
    # phonation pressure), F0 in [50, 400], no extreme aspiration.
    voiced_mask = (pressure > 4000.0)
    if np.any(voiced_mask):
        e_inj_voiced = float(np.sum(e_inj_per_frame[voiced_mask]))
        e_rad_voiced = float(np.sum(e_rad_per_frame[voiced_mask]))
    else:
        e_inj_voiced = e_inj
        e_rad_voiced = e_rad

    # Audio is in [-1, 1] post 1e-7 scaling in TEA's output stage — so the
    # absolute energy ratio between PR² (dPa²) and audio² (dimensionless) is
    # ~1e-14. The gate is *not* a strict ratio; it's a positivity + finiteness
    # + "voiced-frame radiated energy increases monotonically with injected
    # energy" sanity check.
    voiced_passes = (
        np.isfinite(e_inj_voiced)
        and np.isfinite(e_rad_voiced)
        and e_inj_voiced >= 0
        and e_rad_voiced >= 0
        and (e_inj_voiced > 0 if np.any(voiced_mask) else True)
    )
    # Stronger gate: when injected proxy is below 1% of mean (silence frames),
    # radiated should also be small (not exceed 5% of voicing-mean radiated).
    silent_mask = (pressure < 100.0)
    if np.any(silent_mask) and np.any(voiced_mask):
        rad_silent = float(np.mean(e_rad_per_frame[silent_mask]))
        rad_voiced = float(np.mean(e_rad_per_frame[voiced_mask]))
        ratio_silent_to_voiced = rad_silent / max(rad_voiced, 1e-30)
    else:
        ratio_silent_to_voiced = 0.0

    return {
        "e_inj_total": e_inj,
        "e_rad_total": e_rad,
        "e_inj_voiced": e_inj_voiced,
        "e_rad_voiced": e_rad_voiced,
        "n_voiced_frames": int(np.sum(voiced_mask)),
        "n_silent_frames": int(np.sum(silent_mask)),
        "silent_to_voiced_rad_ratio": ratio_silent_to_voiced,
        "voiced_passes_positivity": bool(voiced_passes),
        # 5% threshold on silent-frame radiation against voiced.
        "silence_radiation_under_5pct": bool(ratio_silent_to_voiced <= 0.05),
        # Combined invariant pass.
        "pass": bool(voiced_passes and ratio_silent_to_voiced <= 0.05),
    }


