def _render_fp32(npz_path: Path) -> np.ndarray:
    """Render fp32 audio for an utterance NPZ; return (N,) float32."""
    import jax  # noqa: F401
    import jax.numpy as jnp
    from tractus_engine_advanced.pipeline import synthesize_dynamic_tube

    data = np.load(npz_path)
    audio, _, _, _ = synthesize_dynamic_tube(
        length_cm=jnp.asarray(data["length_cm"]),
        area_cm2=jnp.asarray(data["area_cm2"]),
        wall_mass=jnp.asarray(data["wall_mass"]),
        wall_resistance=jnp.asarray(data["wall_resistance"]),
        wall_stiffness=jnp.asarray(data["wall_stiffness"]),
        samples_per_frame=int(data["samples_per_frame"]),
        glottis_traj=jnp.asarray(data["glottis_traj"]),
    )
    audio.block_until_ready()
    return np.asarray(audio, dtype=np.float32)


def _render_fp64_batch(n_utterances: int) -> None:
    """Spawn one subprocess (TEA_PRECISION=fp64) and render the full corpus.

    Single subprocess amortizes the JAX JIT compile cost across all utts
    instead of paying it 30× from a per-utt driver. Outputs are written
    to ``WORK_DIR / <utt>.fp64.npz`` (the parent reads them later).
    """
    env = dict(os.environ)
    env["TEA_PRECISION"] = "fp64"
    runner = REPO_ROOT / "scripts" / "_render_fp64_batch.py"
    cmd = [sys.executable,
           str(runner), "--n-utterances", str(n_utterances)]
    subprocess.run(cmd, env=env, check=True, cwd=str(REPO_ROOT))


