def _audio_rmse(a: np.ndarray, b: np.ndarray) -> float:
    n = min(len(a), len(b))
    if n == 0:
        return float("inf")
    diff = a[:n].astype(np.float64) - b[:n].astype(np.float64)
    return float(np.sqrt(np.mean(diff**2)))


def _log_mel_l1_db(a: np.ndarray, b: np.ndarray, sr: int) -> float:
    """Log-mel spectrogram L1 distance in dB. Mirrors correctness/001's
    escape-valve metric: audio with raw RMSE > 1e-3 still counts as
    fp32-vs-fp64-equivalent if log-mel L1 ≤ 0.5 dB."""
    import librosa
    n = min(len(a), len(b))
    a = a[:n].astype(np.float32)
    b = b[:n].astype(np.float32)
    mel_a = librosa.feature.melspectrogram(
        y=a, sr=sr, n_fft=2048, hop_length=512, n_mels=64,
    )
    mel_b = librosa.feature.melspectrogram(
        y=b, sr=sr, n_fft=2048, hop_length=512, n_mels=64,
    )
    log_a = librosa.power_to_db(mel_a + 1e-12)
    log_b = librosa.power_to_db(mel_b + 1e-12)
    return float(np.mean(np.abs(log_a - log_b)))


def _f0_rmse_cents(a: np.ndarray, b: np.ndarray, sr: int) -> float:
    """F0 RMSE in cents between two audio buffers (pyin)."""
    import librosa
    f_a, _, _ = librosa.pyin(a, fmin=50.0, fmax=600.0, sr=sr)
    f_b, _, _ = librosa.pyin(b, fmin=50.0, fmax=600.0, sr=sr)
    n = min(len(f_a), len(f_b))
    fa = f_a[:n]
    fb = f_b[:n]
    mask = np.isfinite(fa) & np.isfinite(fb) & (fa > 0) & (fb > 0)
    if not np.any(mask):
        return 0.0
    cents = 1200.0 * np.log2(fa[mask] / fb[mask])
    return float(np.sqrt(np.mean(cents**2)))


def _spectral_tilt(y: np.ndarray, sr: int) -> float:
    """dB/octave linear regression on log10|S(f)| over 100Hz-4kHz."""
    import librosa
    S = np.abs(librosa.stft(y, n_fft=2048, hop_length=512))
    spec = np.mean(S, axis=1)
    freqs = librosa.fft_frequencies(sr=sr, n_fft=2048)
    band = (freqs >= 100.0) & (freqs <= 4000.0) & (spec > 1e-9)
    if not np.any(band):
        return 0.0
    log_f = np.log10(freqs[band])
    log_mag_db = 20.0 * np.log10(spec[band])
    slope, _ = np.polyfit(log_f, log_mag_db, 1)
    return float(slope * np.log10(2.0))


def _frication_db(y: np.ndarray, sr: int) -> dict[str, float]:
    """Energy in 4-6 / 6-8 / 8-11 kHz bands (dB)."""
    import librosa
    S = np.abs(librosa.stft(y, n_fft=2048, hop_length=512))
    freqs = librosa.fft_frequencies(sr=sr, n_fft=2048)
    out = {}
    for name, (lo, hi) in [("4-6kHz", (4000, 6000)), ("6-8kHz", (6000, 8000)), ("8-11kHz", (8000, 11000))]:
        mask = (freqs >= lo) & (freqs < hi)
        if not np.any(mask):
            out[name] = -120.0
            continue
        e = np.mean(S[mask, :] ** 2)
        out[name] = float(10.0 * np.log10(e + 1e-12))
    return out


def _nasal_proxy(y: np.ndarray, sr: int) -> float:
    """Low-band (200-1000Hz) power share of the in-voice band (200-4000Hz).

    The numerator is *total* power in the low band, the denominator is
    *total* power in the full band — so the ratio is bounded in [0, 1].
    The pre-fix mean/mean form was unbounded (means over different
    bin-widths can produce ratios > 1).
    """
    import librosa
    S = np.abs(librosa.stft(y, n_fft=2048, hop_length=512)) ** 2
    freqs = librosa.fft_frequencies(sr=sr, n_fft=2048)
    low = (freqs >= 200) & (freqs < 1000)
    full = (freqs >= 200) & (freqs < 4000)
    e_low = np.sum(S[low, :])
    e_full = np.sum(S[full, :]) + 1e-12
    return float(e_low / e_full)


def _formants_lpc(y: np.ndarray, sr: int, n_formants: int = 3) -> list[float]:
    import librosa
    n_lpc = 2 + sr // 1000
    try:
        a = librosa.lpc(y.astype(np.float64), order=n_lpc)
    except Exception:
        return [float("nan")] * n_formants
    roots = np.roots(a)
    roots = roots[np.imag(roots) >= 0.0]
    angles = np.arctan2(np.imag(roots), np.real(roots))
    freqs = sorted(angles * (sr / (2.0 * np.pi)))
    formants = [f for f in freqs if 90.0 < f < 5500.0]
    formants = formants[:n_formants]
    while len(formants) < n_formants:
        formants.append(float("nan"))
    return [float(f) for f in formants]


